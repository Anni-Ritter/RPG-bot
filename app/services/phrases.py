def pick(values: tuple[str, ...]) -> str:
    return random.choice(values)


def custom_quest_created() -> str:
    pool = CUSTOM_QUEST_CREATED_SELIN if random.random() < 0.7 else CUSTOM_QUEST_CREATED_TORI
    return pick(pool)


def custom_quest_done() -> str:
    pool = CUSTOM_QUEST_DONE_SELIN if random.random() < 0.7 else CUSTOM_QUEST_DONE_TORI
    return pick(pool)


def snack_reaction(count: int) -> str:
    key = min(count, 4)
    if count >= 5:
        return "Селин: — Пять перекусов. Ты сегодня решила существовать исключительно на мелочах?"
    return pick(SNACK_REACTIONS[key])
