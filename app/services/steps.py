def evaluate_steps(steps: int) -> StepTier:
    steps = max(0, steps)
    for tier in STEP_TIERS:
        if tier.max_steps is None or steps <= tier.max_steps:
            if steps >= tier.min_steps:
                return tier
    return STEP_TIERS[-1]
